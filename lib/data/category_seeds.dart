      .map((s) => CategoryModel(
            id: CategoryUtils.key(s['name'] as String),
            name: s['name'] as String,
            icon: s['icon'] as String,
            keywords: List<String>.from(s['keywords'] as List),
            isIncome: false,
            isBuiltIn: true,
          ))
      .toList();

  static List<CategoryModel> get builtInIncomeCategories => _incomeSeeds
      .map((s) => CategoryModel(
            // 'income_' prefix keeps income ids in their own namespace — an
            // expense category and an income category can share a display
            // name (e.g. "أخرى") without colliding on the same doc id.
            id: 'income_${CategoryUtils.key(s['name'] as String)}',
            name: s['name'] as String,
            icon: s['icon'] as String,
            keywords: List<String>.from(s['keywords'] as List),
            isIncome: true,
            isBuiltIn: true,
          ))
      .toList();

